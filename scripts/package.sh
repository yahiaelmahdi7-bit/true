#!/usr/bin/env bash
# Build the SwiftPM executable and assemble it into True.app -- no Xcode required.
# Never launches the app. ASCII-only on purpose (non-ASCII next to $vars breaks under some locales).
# Usage: scripts/package.sh [debug|release]
set -euo pipefail
cd "$(dirname "$0")/.."

CONFIG="${1:-release}"   # release by default: a debug True drew its terminals ~unoptimized (2026-10-14 lag)
APP="${TRUE_APP_OUT:-True.app}"   # make-kit.sh points this at dist/
BIN="True"
BUNDLE_ID="net.prismlens.true"
VERSION="1.2.2"

# make-kit.sh passes a prebuilt (universal) binary and asks for ad-hoc signing: TRUE_PREBUILT_BIN, TRUE_SIGN=adhoc.
if [ -n "${TRUE_PREBUILT_BIN:-}" ]; then
  BIN_PATH="$TRUE_PREBUILT_BIN"
else
  echo "==> swift build ($CONFIG)..."
  nice -n 10 swift build -j 4 -c "$CONFIG"
  BIN_DIR="$(swift build -c "$CONFIG" --show-bin-path)"
  BIN_PATH="$BIN_DIR/$BIN"
fi
[ -f "$BIN_PATH" ] || { echo "ERROR: build product not found at $BIN_PATH"; exit 1; }

echo "==> assembling $APP ..."
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS"
cp "$BIN_PATH" "$APP/Contents/MacOS/$BIN"
# Cursive-T icon (generated by scripts/make-icon.swift; re-run that to change it).
mkdir -p "$APP/Contents/Resources"
cp Assets/AppIcon.icns "$APP/Contents/Resources/AppIcon.icns"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>True</string>
  <key>CFBundleDisplayName</key><string>True</string>
  <key>CFBundleIdentifier</key><string>${BUNDLE_ID}</string>
  <key>CFBundleVersion</key><string>${VERSION}</string>
  <key>CFBundleShortVersionString</key><string>${VERSION}</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleExecutable</key><string>${BIN}</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>LSMinimumSystemVersion</key><string>14.0</string>
  <key>NSHighResolutionCapable</key><true/>
  <key>NSAppTransportSecurity</key><dict><key>NSAllowsArbitraryLoads</key><true/></dict>
  <key>NSPrincipalClass</key><string>NSApplication</string>
  <!-- macOS charges a child process's mic use to the app that launched it, so Claude Code's
       hold-space voice mode asks as True. Without this key TCC refuses silently, no prompt. -->
  <key>NSMicrophoneUsageDescription</key><string>Programs you run in True, such as Claude Code voice mode, use the microphone to hear you.</string>
  <key>NSAppleEventsUsageDescription</key><string>Programs you run in True, such as osascript, use Apple Events to control other apps.</string>
  <!-- Bluetooth advertising (CBPeripheralManager) only notices an unpaired iPhone nearby so the pairing card can appear. -->
  <key>NSBluetoothAlwaysUsageDescription</key><string>True uses Bluetooth only to notice your iPhone nearby so the pairing code can appear.</string>
  <!-- Run 39: "On this network" finds other Macs running True over Bonjour while the Peers window is open. -->
  <key>NSLocalNetworkUsageDescription</key><string>True finds other Macs running True on this network so you can pair with a click.</string>
  <key>NSBonjourServices</key><array><string>_true-peer._tcp</string></array>
</dict>
</plist>
PLIST

# Sign with a stable self-signed identity, NOT ad-hoc. macOS keys every privacy grant (Music, Desktop,
# Documents, ...) to the app's designated requirement. Ad-hoc pins that to the binary's cdhash, so each
# rebuild reads as a brand-new app and every permission popup comes back. A certificate makes the
# requirement cert-based, so "Allow" survives rebuilds. Same identity and reasoning as deck/build.sh.
IDENTITY="Deck Signing"
KEYCHAIN="$HOME/Library/Keychains/deck-signing.keychain-db"
if [ "${TRUE_SIGN:-}" != "adhoc" ] && security find-certificate -c "$IDENTITY" "$KEYCHAIN" >/dev/null 2>&1; then
  # The signing keychain has a blank password and relocks itself; unlock it here or macOS pops a
  # password dialog that the Mac login password does not satisfy.
  security unlock-keychain -p "" "$KEYCHAIN" >/dev/null 2>&1 || true
  codesign --force --sign "$IDENTITY" --keychain "$KEYCHAIN" "$APP"
  codesign --verify --strict "$APP"
  echo "    signed with '$IDENTITY' (permission grants survive rebuilds)"
else
  [ "${TRUE_SIGN:-}" = "adhoc" ] || {
    echo "WARNING: no '$IDENTITY' certificate in $KEYCHAIN -- falling back to ad-hoc."
    echo "         Every permission popup will return after this build. See deck/build.sh to recreate it."; }
  codesign --force --deep --sign - "$APP" >/dev/null 2>&1 && echo "    ad-hoc signed"
  codesign --verify --strict "$APP"
fi
echo "OK: built $APP (not launched)"
